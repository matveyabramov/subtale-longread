import { readFile, readdir, writeFile, mkdir, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const checkOnly = process.argv.includes('--check');
const readJson = async (name) => JSON.parse(await readFile(path.join(root, 'docs', name), 'utf8'));
const figma = await readJson('FIGMA_ASSET_MAP.json');
const delivery = await readJson('ASSET_DELIVERY.json');

// Read provenance at generation time; never import these source manifests into the app.
const images = {};
const hashes = {};
const posters = {};

async function deliveryPath(optimizedPath) {
  if (!optimizedPath.startsWith('public/assets/') || optimizedPath.includes('..')) {
    throw new Error(`Not a public delivery path: ${optimizedPath}`);
  }
  await access(path.join(root, optimizedPath));
  return optimizedPath.slice('public/'.length);
}

function insert(target, key, value) {
  if (key in target && target[key] !== value) throw new Error(`Conflicting asset key: ${key}`);
  target[key] = value;
}

for (const source of figma.sources) {
  if (!source.optimizedPath) continue; // No fallback to source-assets or localPath.
  const url = await deliveryPath(source.optimizedPath);
  insert(images, path.parse(source.optimizedPath).name, url);
  insert(hashes, source.hash, url);
}

for (const item of delivery.assets) {
  if (!item.optimizedPath) continue;
  const url = await deliveryPath(item.optimizedPath);
  if (item.imageHash) {
    if (hashes[item.imageHash] !== url) throw new Error(`Registry mismatch: ${item.imageHash}`);
  } else if (item.optimizedPath.startsWith('public/assets/videos/posters/')) {
    insert(posters, path.parse(item.optimizedPath).name, url);
  }
}

async function publicFiles(directory, extension) {
  const entries = await readdir(path.join(root, 'public/assets', directory));
  const result = {};
  for (const name of entries.sort()) {
    if (!name.endsWith(extension)) continue;
    insert(result, path.parse(name).name, await deliveryPath(`public/assets/${directory}/${name}`));
  }
  return result;
}

// SVGs and original MP4s have no optimizedPath; use their existing public files only.
const vectors = await publicFiles('illustrations', '.svg');
const videos = await publicFiles('videos', '.mp4');
for (const name of Object.keys(videos)) {
  if (!(name in posters)) throw new Error(`Missing poster: ${name}`);
}

const serialize = (name, values) => {
  const entries = Object.entries(values).sort(([a], [b]) => a.localeCompare(b));
  return `export const ${name} = {\n${entries.map(([key, url]) =>
    `  ${JSON.stringify(key)}: assetUrl(${JSON.stringify(url)}),`).join('\n')}\n} as const;\n`;
};

const output = [
  '// Generated by scripts/generate-runtime-assets.mjs. Do not edit manually.',
  '// String URLs only: no source archive, image bytes, eager loading or manifest imports.',
  'const assetUrl = (publicPath: string) => `${import.meta.env.BASE_URL}${publicPath}`;\n',
  serialize('imageAssets', images),
  serialize('imageAssetsByHash', hashes),
  serialize('posterAssets', posters),
  serialize('vectorAssets', vectors),
  serialize('videoAssets', videos),
].join('\n');

const outputPath = path.join(root, 'src/assets/generated.ts');
const current = await readFile(outputPath, 'utf8').catch((error) => {
  if (error.code !== 'ENOENT') throw error;
  return '';
});
if (checkOnly && current !== output) throw new Error('Runtime asset catalogue is stale. Run npm run assets:generate.');
if (!checkOnly && current !== output) {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, output);
}
console.log(`Delivery catalogue ${checkOnly ? 'verified' : 'generated'}: ${Object.keys(images).length} images, ${Object.keys(posters).length} posters, ${Object.keys(vectors).length} SVGs, ${Object.keys(videos).length} MP4s.`);
