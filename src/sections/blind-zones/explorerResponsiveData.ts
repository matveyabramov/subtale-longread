// CSS length arithmetic interpolates the artwork alone, never the whole section.
export function responsiveArtStyle(
  key: `${ExplorerCategoryId}${MeaningState}-${number}`,
  wide: readonly [number, number, number, number],
) {
  const [desktop, tablet, phone] = responsiveArtSlots[key as keyof typeof responsiveArtSlots];
  return responsiveSlotStyle(wide, [desktop, tablet, phone]);
}

type ArtSlot = readonly [number, number, number, number];

export function responsiveSlotStyle(wide: ArtSlot, [desktop, tablet, phone]: readonly [ArtSlot, ArtSlot, ArtSlot]) {
  const properties: Record<string, string> = {};
  const axes = ['x', 'y', 'width', 'height'] as const;
  for (const index of [0, 1, 2, 3] as const) {
    const axis = axes[index];
    const slope = (wide[index] - desktop[index]) / 480;
    properties[`--wide-${axis}`] = `calc(${desktop[index]} * var(--wide-unit) + ${slope} * var(--wide-growth))`;
    // The stacked art region starts after a common description slot in Figma.
    const mobile = phone[index] - (index === 1 ? 366 : 0);
    const target = tablet[index] - (index === 1 ? 497 : 0);
    const origin = index === 0 ? 15 : index === 1 ? 222.5 : 0;
    properties[`--stack-${axis}`] = `calc(${origin}px + ${mobile - origin} * var(--phone-unit) + ${(target - mobile) / 378} * var(--stack-growth))`;
  }
  return properties;
}
